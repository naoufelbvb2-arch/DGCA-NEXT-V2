def test_cf_g2_eos_mechanistic_evidence(experiment_data: dict):
    """CF-G2: Verify elimination of premature EOS activation and restoration of EOS margin."""
    eos = experiment_data["eos_traces"]
    ea = eos["group_a"]
    eb = eos["group_b"]

    # 1. Subject event (Point 1): EOS should be 0 in both
    for cid, a_val in ea["point_1_subject_a_plus"].items():
        assert a_val == 0.0
    for cid, a_val in eb["point_1_subject_a_plus"].items():
        assert a_val == 0.0

    # 2. Verb event (Point 2): Group A has premature activation; Group B has EXACTLY ZERO
    assert max(ea["point_2_verb_pt"].values()) > 0.85
    assert max(ea["point_2_verb_a_plus"].values()) > 0.48

    assert max(eb["point_2_verb_pt"].values()) == 0.0
    assert max(eb["point_2_verb_a_plus"].values()) == 0.0

    # 3. Post-object differential gain (Point 5):
    # Group A: Self-saturation causes Gain = 0.0, Score = 0.0
    for cid, gain in ea["point_5_differential_gain"].items():
        assert gain == 0.0

    # Group B: Zero control activation (A_ctrl = 0.0), Gain > 0.40, Score > 0.40
    for cid, a_ctrl in eb["point_5_next_control_a"].items():
        assert a_ctrl == 0.0
    assert max(eb["point_5_differential_gain"].values()) > 0.40

    # Group B cleanly terminates with GEN_STOP_EOS when object is present
    assert eb["post_object_status"] == StatusCode.OK.name
    assert eb["post_object_winner_assembly_id"] in eb["eos_assembly_ids"]
    assert eb["post_object_top_score"] > 0.50
    assert eb["post_object_margin"] > M_READ


def test_cf_g3_generation_probe_outcomes(experiment_data: dict):
    """CF-G3: Verify generation and readout behavior for all probes at 56 and 112 roots."""
    p_a_56 = experiment_data["probes"]["group_a_56"]
    p_a_112 = experiment_data["probes"]["group_a_112"]
    p_b_56 = experiment_data["probes"]["group_b_56"]
    p_b_112 = experiment_data["probes"]["group_b_112"]

    # Group A at 56
    assert p_a_56["P1"]["stop_status"] == "GEN_STOP_NO_MATCH"
    assert p_a_56["P1"]["emitted_surfaces"] == []
    assert p_a_56["P2"]["stop_status"] == "GEN_STOP_READOUT_UNKNOWN"
    assert p_a_56["P2"]["emitted_surfaces"] == ["الماء"]
    assert p_a_56["P3"]["stop_status"] == "GEN_STOP_NO_MATCH"
    assert p_a_56["P3"]["emitted_surfaces"] == ["التفاح"]
    assert p_a_56["P4"]["stop_status"] == "GEN_STOP_NO_MATCH"
    assert p_a_56["P4"]["emitted_surfaces"] == ["الماء"]

    # Group B at 56: Ambiguity due to duplicate assemblies
    assert p_b_56["P1"]["stop_status"] == "GEN_STOP_NO_MATCH"
    assert p_b_56["P2"]["stop_status"] == "GEN_STOP_AMBIGUOUS"
    assert p_b_56["P3"]["stop_status"] == "GEN_STOP_AMBIGUOUS"
    assert p_b_56["P4"]["stop_status"] == "GEN_STOP_AMBIGUOUS"

    # Group B at 112: P1 emits 'حليب', P3 emits 'تفاح'
    assert p_b_112["P1"]["stop_status"] == "GEN_STOP_NO_MATCH"
    assert p_b_112["P1"]["emitted_surfaces"] == ["حليب"]
    assert p_b_112["P3"]["stop_status"] == "GEN_STOP_NO_MATCH"
    assert p_b_112["P3"]["emitted_surfaces"] == ["تفاح"]


