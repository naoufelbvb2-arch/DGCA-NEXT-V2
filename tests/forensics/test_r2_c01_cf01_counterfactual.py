def test_cf_g4_weak_branch_dilution_and_root30_pruning(experiment_data: dict):
    """CF-G4: Verify candidate deadline expiration at Root 30 occurs in both groups."""
    syns = experiment_data["synapse_lifecycles"]
    sa = syns["group_a"]
    sb = syns["group_b"]

    # In both groups, at Root 25, candidate synapses from 'يشرب' to object exist
    assert "25" in sa
    assert "25" in sb

    # Clock at Root 25 is 100 events
    assert sa["25"]["clock"] == 100
    assert sb["25"]["clock"] == 100

    # At Root 30, direct candidate synapses from 8327 to milk/milk_indefinite were pruned
    # and not present with confirmed_roots starting at 1
    if "30" in sa:
        for k, syn in sa["30"]["synapses"].items():
            if syn["target_id"] in (9731, 9910, 9951):
                assert syn["state"] != "CONSOLIDATED"

    # Re-created by Root 33 with fresh birth event > 100
    assert "33" in sa
    assert "33" in sb


