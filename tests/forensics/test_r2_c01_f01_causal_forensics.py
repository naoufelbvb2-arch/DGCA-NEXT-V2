def test_f01_s02_candidate_specific_saturation_vs_asm9(forensic_data: dict):
    """F01-S02: Verify saturation is candidate-specific, allowing Assembly 9 headroom."""
    s02 = forensic_data["s02_step_traces"]

    # P2 Step 1: Assembly 9 wins with score > theta_read (0.08)
    p2_step1 = s02["P2"]["steps"][1]
    assert p2_step1["winner_assembly_id"] == 9
    assert p2_step1["winner_generation"] == 3
    assert p2_step1["top_score"] > 0.08
    assert abs(p2_step1["top_score"] - 0.096262) < 1e-4

    # EOS (Assembly 2) in P2 Step 1 has score 0.0
    top_cands = {c["assembly_id"]: c["score"] for c in p2_step1["top_candidates"]}
    assert top_cands.get(2, 0.0) == 0.0

    # EOS cells in Step 1 have A_ctrl = 1.0, A_full = 1.0, gain = 0.0
    s05 = forensic_data["s05_eos_pathways"]["r2_c01"]
    for cid_str, gain in s05["step1_gain"].items():
        assert gain == 0.0
        assert s05["step1_a_ctrl"][cid_str] == 1.0
        assert s05["step1_a_full"][cid_str] == 1.0


def test_f01_s03_associative_dilution_and_root30_pruning(forensic_data: dict):
    """F01-S03: Verify dilution causes Root 30 pruning for 'يشرب' -> 'الحليب'."""
    s03_56 = forensic_data["s03_associative_pathways"]["root56"]

    # 'يشرب' -> 'الحليب' direct synapses
    drink_to_milk = s03_56["drink_to_milk"]
    assert len(drink_to_milk) > 0
    for key, syn in drink_to_milk.items():
        # Re-created after Root 30 pruning
        assert syn["state"] == "CANDIDATE"
        assert syn["E_ext"] < 3.0  # Not consolidated
        assert 1 not in syn["confirmed_roots"]  # Initial roots 1, 5, 9, etc. were pruned
        assert syn["confirmed_roots"][0] == 33  # First confirmation of re-created synapse

    # 'يشرب' -> 'الماء' direct synapses
    drink_to_water = s03_56["drink_to_water"]
    assert len(drink_to_water) > 0
    for key, syn in drink_to_water.items():
        assert syn["state"] == "CONSOLIDATED"
        assert syn["E_ext"] > 3.0
        assert min(syn["confirmed_roots"]) <= 6  # Survived from early training (root 4 or 6)


