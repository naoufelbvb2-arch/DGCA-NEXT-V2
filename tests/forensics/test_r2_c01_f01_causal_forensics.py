def test_f01_s05_eos_premature_activation_contrast(forensic_data: dict):
    """F01-S05: Contrast premature EOS activation in R2-C01 vs historical Cat/Eagle."""
    s05 = forensic_data["s05_eos_pathways"]
    r2_c01 = s05["r2_c01"]
    hist = s05["historical_cat_eagle"]

    # In R2-C01: at event 1 ('يشرب'), EOS cells receive P^T > 0.85 and A^+ > 0.48
    for cid_str, pt in r2_c01["ev1_drink_pt"].items():
        assert pt > 0.85
    for cid_str, a_plus in r2_c01["ev1_drink_a_plus"].items():
        assert a_plus > 0.48

    # In Historical Cat/Eagle: at event 1 ('يشرب'), EOS cells have exactly A^+ = 0.0
    for cid_str, a_plus in hist["ev1_drink_a_plus"].items():
        assert a_plus == 0.0

    # Historical Step 1 cleanly halts with GEN_STOP_EOS
    assert hist["step1_stop_status"] == StatusCode.GEN_STOP_EOS.name
    assert hist["step1_winner_assembly_id"] == 2
    assert hist["step1_top_score"] > 0.64


