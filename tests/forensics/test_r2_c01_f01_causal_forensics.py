def test_f01_s07_morphological_overlap(forensic_data: dict):
    """F01-S07: Verify prefix cell sharing across all definite nominal surfaces."""
    s07 = forensic_data["s07_morphological_overlap"]
    prefix = s07["prefix_sharing"]

    definite_nominals = ["القط", "النسر", "الطفل", "الحليب", "الماء", "التفاح"]
    verbs = ["يشرب", "يأكل"]

    for nom in definite_nominals:
        assert prefix[nom]["contains_8416"] is True
        assert prefix[nom]["contains_8575"] is True
        assert prefix[nom]["contains_8586"] is True
        assert prefix[nom]["fixed_support"] == 900000

    for verb in verbs:
        assert prefix[verb]["contains_8416"] is False
        assert prefix[verb]["contains_8575"] is False
        assert prefix[verb]["contains_8586"] is False
        assert prefix[verb]["fixed_support"] == 0
